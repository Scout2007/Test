def approach(d, a, v_cruise):
    """Accelerate to v_cruise, coast, brake at the same a. Returns time."""
    d_acc = v_cruise ** 2 / (2 * a)
    if 2 * d_acc >= d:
        return 2 * math.sqrt(d / a), math.sqrt(a * d)
    return 2 * v_cruise / a + (d - 2 * d_acc) / v_cruise, v_cruise


