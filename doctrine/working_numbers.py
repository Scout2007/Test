def radar_range(P, D, lam, sigma_t, T_sys=100, B=1e3, snr=13, eff=0.6):
    Gain = eff * (math.pi * D / lam) ** 2
    k = 1.380649e-23
    return (P * Gain ** 2 * lam ** 2 * sigma_t /
            ((4 * math.pi) ** 3 * k * T_sys * B * snr)) ** 0.25


