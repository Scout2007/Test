def missile_tof(R, a, dv, reserve, v0=0.0):
    """Boost with (1-reserve)*dv, then coast. v0 = launcher closing speed."""
    dv_use = dv * (1 - reserve)
    tb = dv_use / a
    db = v0 * tb + 0.5 * a * tb * tb
    if db >= R:
        # reach target while still boosting
        t = (-v0 + math.sqrt(v0 * v0 + 2 * a * R)) / a
        return t, v0 + a * t
    vc = v0 + dv_use
    return tb + (R - db) / vc, vc


