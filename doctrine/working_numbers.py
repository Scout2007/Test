def laser_kills(D, lam, P, tr, F, Vc, R_max, R_min, t_re):
    n, R, dR = 0.0, R_max, (R_max - R_min) / 20000
    while R > R_min:
        t_kill = F / intensity(P, D, lam, R, tr)
        n += (dR / Vc) / (t_kill + t_re)
        R -= dR
    return n


