def fmt(x, unit="", digits=3):
    """Compact engineering format."""
    if x == 0:
        return f"0 {unit}".strip()
    a = abs(x)
    if a >= 1e5 or a < 1e-2:
        s = f"{x:.{digits-1}e}"
        m, e = s.split("e")
        s = f"{m}e{int(e)}"
    elif a >= 100:
        s = f"{x:,.0f}"
    elif a >= 10:
        s = f"{x:.1f}"
    else:
        s = f"{x:.2f}"
    return f"{s} {unit}".strip()


def dur(t):
    """Seconds to a readable duration."""
    if t < 1:
        return f"{t*1000:.0f} ms"
    if t < 120:
        return f"{t:.1f} s"
    if t < 7200:
        return f"{t/60:.1f} min"
    if t < 2 * 86400:
        return f"{t/3600:.1f} h"
    return f"{t/86400:.1f} d"


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


