"""Operation Tidebreak: storyboard data (phase 2, revision 5).

One source for the storyboard page, shots.csv, shots.md and ASSET_REQUESTS.md.
Build with:  python3 storyboard/build_storyboard.py

Revision 5 applies the round 4 reviews (review/round4/*.md, synthesis in
review/round4/synthesis.md) and three user requests: the eclipse (Q16), a text
prologue, and dialogue that carries the story on its own, tested by a cold read
(review/coldread/). Revision 3 added the user's five weapon close-ups.

Conventions
- `dur` is screen time in seconds at 24 fps; frames are computed from it.
- `clock` is real mission time at the start of the shot (T+h:mm:ss from warp exit).
- `real` says how the shot treats time: "1:1", "compressed N×", "slowed N×", or a clock jump.
  Every jump of 30 minutes or more says the digits roll. `end` gives the end clock
  when the rate can't be stated as one number.
- `body` is the camera body (CAMERA_BODIES): only hull cameras hear the ship.
- `see` is what a viewer sees, in plain words, with no lore the film doesn't give; with the
  lines, the on-screen text and the sound it makes the audience script the cold read uses.
- The lines are fleet traffic: callsigns, reports, orders and acknowledgments, reacting to what
  just happened. They never explain what the crew already knows.
- `cps` lets a title card read faster than the 12 characters a second subtitles get.
- `comm` lines may carry a third value, the second in the shot where the line starts (its cue),
  when it waits for an event. Shots that share a `group` share one reading window, so an
  exchange can run over quick cuts; `world` overrides the map's World preset.
- `hud` lists the text on screen besides the subtitles (plot labels, the HEAT readout);
  it counts toward the reading-speed ceiling.
- `rules` cite doctrine rule IDs (doctrine/LREF_doctrine.md, doctrine/Defence_doctrine.md).
- `assets` cite IDs in ASSETS; `rig` names Endeavor rig properties
  (pack/project_docs/README_blender_project.md) or ones requested in ASSETS (marked "new").
- `cost` is the render class in RENDER_CLASSES; MEASURED replaces a class's estimate
  once the step 1 benchmarks have timed it.
- `sketch` is a call into storyboard/sketchlib.js; `render` is a current Blender
  frame used as look reference. Sketches drop the gold shields automatically once
  the shields are parked.
- Text refers to shots by title, as `{#Title}`; the builder turns that into the
  shot's number, so renumbering never breaks a reference.
"""

